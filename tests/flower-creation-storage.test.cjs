const test = require('node:test');
const assert = require('node:assert/strict');
const { createLoader } = require('./helpers/load-ts.cjs');
test('草稿按账号隔离，保留云花瓶落点，拒绝非法数据', () => {
    const records = new Map();
    const loader = createLoader({ uni: { getStorageSync: key => records.get(key), setStorageSync: (key, data) => records.set(key, data), removeStorageSync: key => records.delete(key) } });
    const storage = loader.load('src/utils/flower/creation-storage.ts');
    const store = loader.load('src/stores/artworkStore.ts').useArtworkStore();
    store.addFlower('rose');
    const artwork = store.snapshot();
    artwork.vaseMaterialId = 'ceramic-vase';
    artwork.vaseMaterialRevision = '1234567890abcdef';
    artwork.stems[0].x = 300;
    const draft = { version: 1, artwork, card: { blessing: '你好', signature: '' }, updatedAt: 123 };
    storage.writeDraft('a', draft);
    draft.artwork.stems[0].x = 400;
    assert.equal(storage.readDraft('a').artwork.stems[0].x, 300);
    assert.equal(storage.readDraft('b'), null);
    assert.throws(() => storage.writeDraft('a', { ...draft, card: { blessing: '花'.repeat(121), signature: '' } }));
    storage.clearDraft('b');
    assert.ok(storage.readDraft('a'));
    storage.clearDraft('a');
    assert.equal(storage.readDraft('a'), null);
});
