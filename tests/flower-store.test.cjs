const assert = require('node:assert/strict')
const test = require('node:test')
const { createLoader } = require('./helpers/load-ts.cjs')
function setup() {
  const loader = createLoader()
  return { loader, store: loader.load('src/stores/artworkStore.ts').useArtworkStore() }
}

test('store 的清空、撤销、重做与新会话初始化', () => {
  const { store } = setup()
  store.setVase('花束')
  store.clearArtwork()
  assert.equal(store.stems.length, 0)
  store.undo()
  assert.equal(store.stems.length, 3)
  assert.equal(store.vase, '花束')
  store.redo()
  assert.equal(store.stems.length, 0)
  store.initialize()
  assert.equal(store.stems.length, 3)
  assert.equal(store.vase, '陶瓶')
  assert.equal(store.canUndo, false)
  assert.equal(store.canRedo, false)
})

test('工作室页面和子组件共享同一个创作作品 store', () => {
  const { loader } = setup()
  const { useCreationArtworkStore } = loader.load('src/stores/artworkStore.ts')
  const pageStore = useCreationArtworkStore()
  const toolbarStore = useCreationArtworkStore()
  pageStore.initialize()
  pageStore.select(1)
  assert.equal(toolbarStore, pageStore)
  assert.equal(toolbarStore.selected.id, 1)
})

test('store 无效操作不记录历史，新编辑清除重做，花枝数量不设硬性上限', () => {
  const { store } = setup()
  store.select(1)
  store.setColor('#f1e5bd')
  store.setLayer('back')
  assert.equal(store.canUndo, false)
  store.setColor('#b82b36')
  store.undo()
  assert.equal(store.canRedo, true)
  store.addFlower('poppy')
  assert.equal(store.canRedo, false)
  while (store.stems.length < 50) store.addFlower('rose')
  assert.notEqual(store.addFlower('rose'), null)
  store.select(1)
  assert.notEqual(store.duplicateSelected(), null)
  assert.equal(store.stems.length, 52)
  assert.equal(new Set(store.stems.map(stem => stem.id)).size, 52)
})

test('store 快照不共享对象，历史只保留最近30步，JSON预览不污染作品', () => {
  const { store, loader } = setup()
  const snapshot = store.snapshot()
  snapshot.stems[0].color = '#ffffff'
  assert.equal(store.stems[0].color, '#f1e5bd')
  const { parseArtwork } = loader.load('src/utils/flower/artwork.ts')
  parseArtwork(JSON.stringify({ ...snapshot, stems: [] }))
  assert.equal(store.stems.length, 3)
  store.select(1)
  for (let index = 0; index < 35; index++) store.setColor(index % 2 ? '#b82b36' : '#ffffff')
  for (let index = 0; index < 30; index++) store.undo()
  assert.equal(store.canUndo, false)
})

test('store 拖动多次更新仅记录一次历史，空拖动不记录', () => {
  const { store } = setup()
  const original = store.snapshot()
  const origin = store.beginStemEdit(1)
  store.updateStem(1, { ...origin, angle: -15, stemHeight: 420 })
  store.updateStem(1, { ...origin, angle: -10, stemHeight: 440 })
  store.endStemEdit()
  store.undo()
  assert.equal(JSON.stringify(store.snapshot()), JSON.stringify(original))
  assert.equal(store.canUndo, false)
  store.redo()
  assert.equal(store.stems[0].stemHeight, 440)
  store.beginStemEdit(1)
  store.endStemEdit()
  store.undo()
  assert.equal(JSON.stringify(store.snapshot()), JSON.stringify(original))
})
